/**
 * The ADG staging Worker: the Next.js application (through OpenNext) and the ADG API (the
 * unmodified `docker/Dockerfile.backend` image, in a Cloudflare Container), on one origin,
 * behind Cloudflare Access.
 *
 *   request ─► Access at the edge ─► this Worker ─► Access assertion verified (access.ts)
 *                                        ├─ API path (routing.ts) ─► AdgApiContainer :8000
 *                                        └─ everything else ─► OpenNext (Next.js) ─┐
 *                                                server-side API calls ◄───────────┘
 *                                                (lib/api/transport.ts ─► AdgApiContainer)
 *
 * It contains no application logic. See docs/deployment/cloudflare-demo.md.
 */

import { Container, getContainer } from "@cloudflare/containers";
import { env as workerEnv } from "cloudflare:workers";

// @ts-expect-error generated by `opennextjs-cloudflare build`
import { default as openNext } from "../.open-next/worker.js";
import { installApiTransport } from "../lib/api/transport";
import { accessConfiguration } from "./access";
import {
  INTERNAL_API_URL,
  type StagingVariables,
  containerEnvironment,
  frontendEnvironment,
} from "./environment";
import { routeRequest } from "./routing";

export interface Env extends StagingVariables {
  ADG_API: DurableObjectNamespace<AdgApiContainer>;
  ASSETS: Fetcher;
  WORKER_SELF_REFERENCE: Fetcher;
}

/** One API instance: the demo's state is in PostgreSQL, and one process serves a review. */
const API_INSTANCE = "adg-api";

function log(entry: Record<string, unknown>): void {
  console.log(JSON.stringify(entry));
}

/**
 * The API Container. Its whole configuration is its environment — an allow-list built by
 * `containerEnvironment`, which refuses anything but a Null Meridian demo — and its port.
 * It runs the image's own command (`python -m app`): no reset, no migration, no seed. The
 * database is bootstrapped once, by an operator (docs/deployment/cloudflare-demo.md §6).
 */
export class AdgApiContainer extends Container<Env> {
  defaultPort = 8000;
  sleepAfter: string | number = "15m";

  constructor(ctx: Container<Env>["ctx"], env: Env) {
    super(ctx, env);
    this.envVars = containerEnvironment(env);
    const sleepAfter = env.ADG_CONTAINER_SLEEP_AFTER?.trim();
    if (sleepAfter) {
      this.sleepAfter = sleepAfter;
    }
  }

  /**
   * OpenNext replaces `globalThis.Request` with a subclass for this whole isolate on its first
   * request, and this Durable Object shares the isolate. The Containers library recognizes a
   * request by `instanceof Request` — the subclass, from then on — so a request arriving here
   * (a runtime Request) would be read as a URL string and fail ("Invalid URL: [object
   * Request]"). Re-wrapping it in whatever `Request` currently is keeps both working.
   */
  override async fetch(request: Request): Promise<Response> {
    const CurrentRequest = globalThis.Request;
    return super.fetch(request instanceof CurrentRequest ? request : new CurrentRequest(request));
  }

  override onStart(): void {
    log({ event: "adg.container.started", instance: API_INSTANCE });
  }

  override onStop(params: { exitCode?: number; reason?: string }): void {
    log({ event: "adg.container.stopped", exit_code: params.exitCode, reason: params.reason });
  }

  override onError(error: unknown): unknown {
    log({
      event: "adg.container.error",
      error: error instanceof Error ? `${error.name}: ${error.message}` : String(error),
    });
    throw error;
  }
}

/** Every request bound for the API, from the edge or from Next.js. */
async function callApi(env: Env, request: Request): Promise<Response> {
  // Validated here as well as in the Container's constructor so that a misconfiguration is
  // a named 503 rather than a Durable Object that fails to construct.
  containerEnvironment(env);
  return getContainer(env.ADG_API, API_INSTANCE).fetch(request);
}

// Next.js reaches the API only through `lib/api/client.ts`, which sends through this.
installApiTransport((request) => callApi(workerEnv as unknown as Env, request));

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    return routeRequest(request, {
      access: accessConfiguration(env),
      api: (forwarded) => callApi(env, forwarded),
      frontend: (forwarded) => openNext.fetch(forwarded, frontendEnvironment(env), ctx),
      log,
    });
  },

  /**
   * Keep-warm (wrangler.jsonc `triggers.crons`). On a `basic` instance the API takes 24-28 s
   * from process start to ready — longer than the web tier's 10 s API timeout — so a page
   * served by a sleeping Container would report the API unreachable. A readiness probe every
   * few minutes keeps the one instance awake (and logs its health); remove the cron to let it
   * sleep instead. Internal only: it never passes through Access, and it reads nothing.
   */
  async scheduled(_controller: ScheduledController, env: Env): Promise<void> {
    const started = Date.now();
    try {
      const response = await callApi(env, new Request(`${INTERNAL_API_URL}/health/ready`));
      log({ event: "adg.keepwarm", status: response.status, ms: Date.now() - started });
    } catch (error) {
      log({
        event: "adg.keepwarm",
        error: error instanceof Error ? `${error.name}: ${error.message}` : String(error),
        ms: Date.now() - started,
      });
    }
  },
} satisfies ExportedHandler<Env>;
