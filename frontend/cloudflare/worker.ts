/**
 * The ADG staging Worker: the Next.js application (through OpenNext) and a same-origin proxy
 * to the ADG API (the unmodified `docker/Dockerfile.backend` image, on Render's free tier).
 * Public: no Cloudflare Access. ADG's own sign-in decides what a visitor may do, and the API
 * answers only requests that carry the Worker's origin key.
 *
 *   request ─► this Worker ─┬─ API path (routing.ts) ─► Render (origin gate) ─► Supabase
 *                           └─ everything else ─► OpenNext (Next.js) ─┐
 *                                   server-side API calls ◄───────────┘
 *                                   (lib/api/transport.ts ─► Render)
 *
 * It contains no application logic. See docs/deployment/cloudflare-demo.md.
 */

import { env as workerEnv } from "cloudflare:workers";

// @ts-expect-error generated by `opennextjs-cloudflare build`
import { default as openNext } from "../.open-next/worker.js";
import { installApiTransport } from "../lib/api/transport";
import { type StagingVariables, apiUpstream, frontendEnvironment } from "./environment";
import { forwardToApi, routeRequest } from "./routing";

export interface Env extends StagingVariables {
  ASSETS: Fetcher;
  WORKER_SELF_REFERENCE: Fetcher;
}

/**
 * How long a server-side API call may wait. Render's free instance sleeps after 15 idle
 * minutes and takes about a minute to wake (docs §7); the web tier's own 10-30 s timeouts
 * would show a waking API as down, so on this host every call gets long enough to wake it.
 */
const API_WAKE_TIMEOUT_MS = 120_000;

function log(entry: Record<string, unknown>): void {
  console.log(JSON.stringify(entry));
}

/** Every request bound for the API, from the edge or from Next.js. */
function callApi(env: Env, request: Request): Promise<Response> {
  return forwardToApi(request, apiUpstream(env));
}

// Next.js reaches the API only through `lib/api/client.ts`, which sends through this.
installApiTransport((request) =>
  callApi(
    workerEnv as unknown as Env,
    new Request(request, { signal: AbortSignal.timeout(API_WAKE_TIMEOUT_MS) }),
  ),
);

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    return routeRequest(request, {
      api: (forwarded) => callApi(env, forwarded),
      frontend: (forwarded) => openNext.fetch(forwarded, frontendEnvironment(env), ctx),
      log,
    });
  },
} satisfies ExportedHandler<Env>;
