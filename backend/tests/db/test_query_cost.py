r"""What a read costs the database, counted rather than timed.

Every other database test here asserts what an endpoint *answers*. This one asserts what it
*does*: how many statements it issues, and whether that number moves with the size of the
answer. Those are different failures. An N+1 returns exactly the right JSON — it is invisible
to every assertion about content, and it is the single defect most likely to make a correct
API unusable on a real estate.

**Counted, never timed.** A millisecond is a fact about the machine the suite happened to run
on, and a threshold in milliseconds is a test that fails on a busy laptop and passes on a
fast one until nobody trusts it. A statement count is a fact about the code: it is the same
number on every machine, and "this request issued nine statements for a hundred rows and nine
for one" is the property an N+1 violates.

Two kinds of assertion, and the difference matters:

  * **the property** — a paged endpoint's statement count must not grow with its page. That
    holds for any implementation and will not need editing when one changes;
  * **an exact count against one table** — ``GET /resources/{path}`` may read
    ``ntfs_resources`` exactly twice, once for the directory and once for its parent. That is
    deliberately tight, because both duplicated reads Phase 3C removed were of exactly this
    shape: a row fetched, and then fetched again in the same request by a different layer
    that did not know it was already in hand.
"""

