@pytest.mark.parametrize("template", PAGED)
async def test_a_paged_read_costs_the_same_whatever_the_page_holds(
    client: AsyncClient, estate: None, statements: StatementLog, template: str
) -> None:
    """The N+1 property, stated as a property.

    A read whose statement count grows with its answer cannot be paged out of trouble: the
    hundredth row costs another round trip, and an estate is where that stops being free.
    """
    with statements:
        one = await client.get(template.format(n=1))
    single = statements.count

    with statements:
        many = await client.get(template.format(n=100))
    hundred = statements.count

    assert one.status_code == 200
    assert many.status_code == 200
    assert single > 0
    assert hundred == single, (
        f"{template} issued {single} statement(s) for one row and {hundred} for a hundred. "
        "A read's cost must not grow with the size of its answer."
    )


async def test_a_directory_detail_reads_the_resource_table_twice(
    client: AsyncClient, estate: None, statements: StatementLog
) -> None:
    """Once for the directory, once for its parent, and not again.

    The boundary verdict has to read the parent to project from it, and the response shows
    that same parent row. Before Phase 3C both layers fetched it independently, so this
    endpoint read the table three times to answer a question about two rows.
    """
    with statements:
        response = await client.get(f"/api/v1/resources/{encoded(REPORTS_UNC)}")

    assert response.status_code == 200
    assert response.json()["parent"] is not None
    assert statements.reading("ntfs_resources") == 2, (
        "GET /resources/{path} should read ntfs_resources once for the directory and once "
        f"for its parent; it read it {statements.reading('ntfs_resources')} times."
    )


async def test_a_share_root_acl_reads_the_resource_table_once(
    client: AsyncClient, estate: None, statements: StatementLog
) -> None:
    """The root is looked up to learn its key, and then not looked up again.

    It has to be read first — the share key alone does not say whether any run has described
    the directory the share publishes — and the ACL response then reports that same row.
    """
    with statements:
        response = await client.get("/api/v1/shares/fs01%7Cfinance/root-acl")

    assert response.status_code == 200
    assert statements.reading("ntfs_resources") == 1, (
        "GET /shares/{share}/root-acl should read ntfs_resources once; it read it "
        f"{statements.reading('ntfs_resources')} times."
    )


async def test_an_acl_page_reads_the_entry_table_a_bounded_number_of_times(
    client: AsyncClient, estate: None, statements: StatementLog
) -> None:
    """Three reads of ``ntfs_aces``: the page, the total, and the digest over the whole DACL.

    The third is unpaged on purpose — a digest over part of a DACL is not a digest of the
    DACL — and it is the reason this count is three rather than two. Pinned so that a fourth
    arriving unnoticed is a failure rather than a slow endpoint nobody can explain.
    """
    with statements:
        response = await client.get(f"/api/v1/resources/{encoded(FINANCE_UNC)}/acl?limit=2")

    assert response.status_code == 200
    assert statements.reading("ntfs_aces") == 3
