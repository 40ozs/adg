def observation(kind: str, run_id: str, index: int, **fields: Any) -> dict[str, Any]:
    return {
        "schema_version": "1.3",
        "kind": kind,
        "run_id": run_id,
        "observed_at": f"2026-09-14T08:{index % 60:02d}:00Z",
        **fields,
    }


def ace(run_id: str, index: int, path: str, trustee: str, order: int) -> dict[str, Any]:
    return observation(
        "ntfs_ace",
        run_id,
        index,
        source_key=keys.ntfs_ace_key(path, Sid(trustee), "allow", MODIFY, 0x03),
        path=path,
        trustee_sid=trustee,
        ace_type="allow",
        access_mask=MODIFY,
        ace_flags=0x03,
        source="explicit",
        order_index=order,
    )


def digest(entries: list[dict[str, Any]]) -> str:
    return acl_hash(
        dacl_present=True,
        dacl_protected=False,
        aces=[
            AclAceFacts(
                trustee_sid=item["trustee_sid"],
                ace_type=AceType(item["ace_type"]),
                access_mask=item["access_mask"],
                ace_flags=item["ace_flags"],
                order_index=item["order_index"],
            )
            for item in entries
        ],
    )


