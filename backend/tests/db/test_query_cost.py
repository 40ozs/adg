def encoded(path: str) -> str:
    return quote(path, safe="")


class StatementLog:
    """Every statement one engine issues while the block is open.

    Attached to the engine rather than to a session so that nothing a request does can escape
    it — including a statement issued by a layer the test does not know about, which is
    exactly the kind an N+1 is made of.
    """

    def __init__(self, engine: Any) -> None:
        self._engine = engine.sync_engine if hasattr(engine, "sync_engine") else engine
        self.statements: list[str] = []

    def _record(self, conn: Any, cursor: Any, statement: str, *rest: Any) -> None:
        self.statements.append(" ".join(statement.split()))

    def __enter__(self) -> StatementLog:
        self.statements = []
        sa.event.listen(self._engine, "before_cursor_execute", self._record)
        return self

    def __exit__(self, *exc: object) -> None:
        sa.event.remove(self._engine, "before_cursor_execute", self._record)

    @property
    def count(self) -> int:
        return len(self.statements)

    def reading(self, table: str) -> int:
        """How many statements selected from one table.

        A crude match on ``FROM <table>`` and ``JOIN <table>``, which is enough: these
        queries are generated by one query builder and spell a table name one way. A count
        that is wrong because the match missed something would be wrong in the safe
        direction — too low, so a duplicated read would look like a single one and the test
        would fail rather than pass quietly.
        """
        pattern = re.compile(rf"\b(?:FROM|JOIN)\s+{re.escape(table)}\b", re.IGNORECASE)
        return sum(1 for statement in self.statements if pattern.search(statement))


@pytest.fixture
def statements(database: Database) -> StatementLog:
    return StatementLog(database.engine)


def observation(kind: str, run_id: str, index: int, **fields: Any) -> dict[str, Any]:
    return {
        "schema_version": "1.3",
        "kind": kind,
        "run_id": run_id,
        "observed_at": f"2026-09-14T08:{index % 60:02d}:00Z",
        **fields,
    }


def ace(run_id: str, index: int, path: str, trustee: str, order: int) -> dict[str, Any]:
    return observation(
        "ntfs_ace",
        run_id,
        index,
        source_key=keys.ntfs_ace_key(path, Sid(trustee), "allow", MODIFY, 0x03),
        path=path,
        trustee_sid=trustee,
        ace_type="allow",
        access_mask=MODIFY,
        ace_flags=0x03,
        source="explicit",
        order_index=order,
    )


def digest(entries: list[dict[str, Any]]) -> str:
    return acl_hash(
        dacl_present=True,
        dacl_protected=False,
        aces=[
            AclAceFacts(
                trustee_sid=item["trustee_sid"],
                ace_type=AceType(item["ace_type"]),
                access_mask=item["access_mask"],
                ace_flags=item["ace_flags"],
                order_index=item["order_index"],
            )
            for item in entries
        ],
    )


