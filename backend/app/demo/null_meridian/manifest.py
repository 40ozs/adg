r"""The Null Meridian manifest: the canon in a form another application can read.

Two documents come from here, both committed under ``docs/demo/``:

* ``null-meridian.manifest.json`` — the summary: company facts, the identifier algorithms,
  every count and distribution the documentation quotes, the golden scenarios, and SHA-256
  digests of the canonical employee, group and membership lists.
* ``null-meridian.canon.json`` — the identity canon itself, one record per line: every
  employee, every group, every nesting and every direct membership on the snapshot date.
  This is what OGWA reads to agree with ADG about who exists. It holds no file-server data.

Both are regenerated by ``python -m app.demo.null_meridian manifest`` and checked by the
test suite, so a change to the canon that is not also a change to these files fails a test.
"""

